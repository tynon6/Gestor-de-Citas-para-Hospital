-- Ejecutar sobre la base principal SanitasFlow.
-- La aplicación también aplica estos cambios de forma idempotente al iniciar.
ALTER TABLE "Medicos" ADD COLUMN IF NOT EXISTS "Activo" boolean NOT NULL DEFAULT TRUE;
ALTER TABLE "Enfermeros" ADD COLUMN IF NOT EXISTS "Activo" boolean NOT NULL DEFAULT TRUE;
ALTER TABLE "Citas" ADD COLUMN IF NOT EXISTS "ReasignacionUrgente" boolean NOT NULL DEFAULT FALSE;
ALTER TABLE "Citas" ADD COLUMN IF NOT EXISTS "AvisoReasignacion" varchar(500);
UPDATE "Citas" SET "AvisoReasignacion" = 'Reasignación de cita por la baja de ' || split_part(split_part("AvisoReasignacion", 'baja de ', 2), '. Requiere', 1)
WHERE "ReasignacionUrgente" = TRUE AND "AvisoReasignacion" LIKE 'Esta cita fue reasignada por la baja de %';

CREATE TABLE IF NOT EXISTS "CuentasMaestras" (
    "Id" integer PRIMARY KEY CHECK ("Id" = 1),
    "NombreUsuario" varchar(40) NOT NULL UNIQUE,
    "PasswordHash" varchar(512) NOT NULL
);

CREATE TABLE IF NOT EXISTS "SolicitudesBajaMedico" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MedicoId" integer NOT NULL,
    "MedicoNombre" varchar(300) NOT NULL,
    "EnfermeroId" integer NOT NULL,
    "EnfermeroNombre" varchar(300) NOT NULL,
    "Motivo" varchar(1000) NOT NULL,
    "Estado" varchar(24) NOT NULL DEFAULT 'Pendiente',
    "CreadaEnUtc" timestamptz NOT NULL,
    "RevisadaPorCuentaId" integer,
    "RevisadaEnUtc" timestamptz,
    "NotaRevision" text
);
CREATE INDEX IF NOT EXISTS "IX_SolicitudesBajaMedico_MedicoId_Estado"
    ON "SolicitudesBajaMedico" ("MedicoId", "Estado");

CREATE TABLE IF NOT EXISTS "MovimientosPersonal" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ActorRol" varchar(30) NOT NULL,
    "ActorId" integer,
    "ActorUsuario" varchar(80) NOT NULL,
    "ActorNombre" varchar(300) NOT NULL,
    "Accion" varchar(80) NOT NULL,
    "DestinoTipo" varchar(40) NOT NULL,
    "DestinoId" integer,
    "DestinoNombre" varchar(300) NOT NULL,
    "Detalle" varchar(1000) NOT NULL,
    "FechaUtc" timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_MovimientosPersonal_FechaUtc"
    ON "MovimientosPersonal" ("FechaUtc");

CREATE TABLE IF NOT EXISTS "MedicosBaja" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MedicoOriginalId" integer NOT NULL,
    "Nombre" varchar(300) NOT NULL,
    "NombreUsuario" varchar(40) NOT NULL,
    "Correo" varchar(320) NOT NULL,
    "EspecialidadId" varchar(100) NOT NULL,
    "Edad" integer NOT NULL,
    "Sexo" text NOT NULL,
    "Motivo" varchar(1000) NOT NULL,
    "SolicitadoPor" text NOT NULL,
    "AprobadoPor" text NOT NULL,
    "DadoDeBajaEnUtc" timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_MedicosBaja_MedicoOriginalId"
    ON "MedicosBaja" ("MedicoOriginalId");

CREATE TABLE IF NOT EXISTS "MedicosBajaCitas" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CitaId" integer NOT NULL,
    "Paciente" varchar(300) NOT NULL,
    "Especialidad" varchar(150) NOT NULL,
    "Procedimiento" varchar(200) NOT NULL,
    "Fecha" date NOT NULL,
    "InicioMin" integer NOT NULL,
    "FinMin" integer NOT NULL,
    "MedicoAnterior" varchar(300) NOT NULL,
    "MedicoDestino" varchar(300),
    "Resultado" varchar(30) NOT NULL,
    "PorcentajeReembolso" integer NOT NULL,
    "MontoReembolso" numeric(10,2) NOT NULL,
    "ProcesadaEnUtc" timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_MedicosBajaCitas_CitaId"
    ON "MedicosBajaCitas" ("CitaId");
